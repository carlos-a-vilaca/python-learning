#Cria um programa que leia 2 valores introduzidos pelo utilizador e que apresente a sua soma, subtração, multiplicação, divisão e resto de divisão.

valor1 = int(input('Insira um valor: '))
valor2 = int(input('Insira o segundo valor: '))

print (valor1 + valor2)
print (valor1 - valor2)
print (valor1 * valor2)
print (valor1 / valor2)
print (valor1 % valor2)